"""The OPxFlasher application icon.

The PNGs in ``assets/`` are generated by ``scripts/build_brand.py`` from
``icon.svg`` and ``icon-small.svg``. PNGs are used at runtime (rather than the
SVG) so the icon works without Qt's SVG image plugin, which frozen builds can
leave out. Sizes up to 32 px come from the small-size drawing.
"""

from __future__ import annotations

import sys
from importlib import resources

from PySide6.QtGui import QIcon, QPixmap

SIZES = (16, 24, 32, 48, 64, 128, 256)
APP_USER_MODEL_ID = "ox1d3x3.OPxFlasher"


def app_icon() -> QIcon:
    """Every packaged size, so Qt never has to scale a tiny icon from a big one."""
    icon = QIcon()
    base = resources.files("opx.gui") / "assets"
    for size in SIZES:
        pm = QPixmap()
        # Read bytes rather than pass a path: works from a zip or a frozen bundle.
        if pm.loadFromData((base / f"icon-{size}.png").read_bytes(), "PNG"):
            icon.addPixmap(pm)
    return icon


def set_windows_app_id() -> None:
    """Group our windows under our own taskbar icon instead of python.exe's."""
    if sys.platform != "win32":
        return
    try:
        import ctypes

        ctypes.windll.shell32.SetCurrentProcessExplicitAppUserModelID(APP_USER_MODEL_ID)
    except (AttributeError, OSError):
        pass
